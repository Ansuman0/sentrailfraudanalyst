"""Every route must say what protects it (request check order, step 4: the required permission).

`route_table(app)` reads the FastAPI dependency tree of each route and classifies it:
  permission  - require(...) / require_any(...): the named permissions
  api_key     - machine access (POST /screen)
  scim        - the identity provider's SCIM token (/scim/v2/*)
  session     - any signed-in person, no permission: only the self-service routes (profile, sessions, two-factor, tenant switching)
  public      - before sign-in or health checks: an explicit allowlist below
A route that is none of these is a violation: `check_routes(app)` raises at start-up, and the unit test fails in CI.
`render_markdown(app)` generates docs/route-permissions.md.
"""
from fastapi.routing import APIRoute

# Reachable without signing in. Adding a route here is a deliberate, reviewed act.
PUBLIC: set[tuple[str, str]] = {
    ("GET", "/healthz"), ("GET", "/readyz"),
    ("POST", "/auth/login"), ("POST", "/auth/mfa"), ("POST", "/auth/refresh"), ("POST", "/auth/discover"), ("POST", "/auth/logout"),
    ("GET", "/auth/oidc/login"), ("GET", "/auth/oidc/callback"), ("GET", "/auth/oidc/logout"),
    ("POST", "/invitations/accept"), ("POST", "/auth/passkey"),
}

# Signed-in routes that need no permission because they only concern the caller's own account.
SELF_SERVICE_PREFIXES = ("/me", "/session/")


def _calls(dependant):
    for d in dependant.dependencies:
        yield d.call
        yield from _calls(d)


def route_table(app) -> list[dict]:
    rows = []
    for r in app.routes:
        if not isinstance(r, APIRoute):
            continue
        calls = [c for c in _calls(r.dependant) if hasattr(c, "sentrail_kind")]
        perms = sorted({p for c in calls if c.sentrail_kind in ("require", "any") for p in c.sentrail_perms})
        if any(c.sentrail_kind in ("require", "any") for c in calls):
            kind = "permission"
        elif any(c.sentrail_kind == "api_key" for c in calls):
            kind = "api_key"
        elif any(c.sentrail_kind == "scim" for c in calls):
            kind = "scim"
        elif any(c.sentrail_kind == "session" for c in calls):
            kind = "session"
        else:
            kind = "none"
        for m in sorted(r.methods - {"HEAD", "OPTIONS"}):
            if kind == "none" and (m, r.path) in PUBLIC:
                kind = "public"
            rows.append({"method": m, "path": r.path, "kind": kind, "perms": perms,
                         "any": any(c.sentrail_kind == "any" for c in calls)})
    return sorted(rows, key=lambda x: (x["path"], x["method"]))


def violations(app) -> list[str]:
    out = []
    for row in route_table(app):
        if row["kind"] == "none":
            out.append(f'{row["method"]} {row["path"]}: no permission declared and not on the public list')
        elif row["kind"] == "session" and not row["path"].startswith(SELF_SERVICE_PREFIXES):
            out.append(f'{row["method"]} {row["path"]}: signed-in only, but not a self-service route (/me*, /session/*)')
    return out


def check_routes(app) -> None:
    bad = violations(app)
    if bad:
        raise RuntimeError("Routes without a declared permission:\n  " + "\n  ".join(bad))


def render_markdown(app) -> str:
    out = ["# Route permissions", "",
           "Generated by `python -m scripts.gen_route_doc` from the running app's dependency tree. Do not edit by hand:",
           "a unit test fails when this file is out of date, and the API refuses to start if a route declares no permission.", "",
           "| Method | Path | Protected by |", "|---|---|---|"]
    for r in route_table(app):
        if r["kind"] == "permission":
            by = ("any of " if r["any"] and len(r["perms"]) > 1 else "") + ", ".join(f"`{p}`" for p in r["perms"])
        elif r["kind"] == "api_key":
            by = "API key (scope `screen`)"
        elif r["kind"] == "scim":
            by = "SCIM token (one tenant, Enterprise plan)"
        elif r["kind"] == "session":
            by = "signed in (own account only)"
        else:
            by = "public (before sign-in)"
        out.append(f'| {r["method"]} | `{r["path"]}` | {by} |')
    return "\n".join(out) + "\n"
